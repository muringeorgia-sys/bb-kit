// Плагин пишет их в папку данных перед запуском треда — в сборке bb нет файлов рядом с server.js.
// ctx: { data, skill, agents, pluginId }

export const draftText = ({ data, pluginId }) => `# Черновик правки скилла prd (тред из панели «Конвейер PRD»)

Ты правишь копию скилла prd по просьбе пользователя. Рабочий скилл и агентов не трогаешь: пользователь сам нажмёт «Принять» в панели.

## Папки черновика

\`D\` = \`${data}/drafts/<id>/\` (id — в задании).

| Что | Где |
|---|---|
| Просьба | \`D/request.md\` |
| Копия скилла | \`D/skill/\` |
| Агенты prd-* | \`D/agents/\` (включены), \`D/agents-disabled/\` (выключены) |
| Итог для панели | \`D/result.json\` — пишешь в конце |

## Как править

1. Прочитай \`D/request.md\`, \`D/skill/SKILL.md\`, \`D/skill/settings.json\`. Остальные файлы — только нужные для правки.
2. Правь только файлы в \`D/\`. Браузер, трекер, вики, другие треды — нельзя.
3. Числа и варианты (лимиты слов и критериев, ревьюер, режим по умолчанию, концепция) — \`settings.json\` → \`params[ключ].value\`.
4. Цепочки Lite и Full — \`settings.json\` → \`flows.lite\` / \`flows.full\`: шаги \`steps\`, агенты \`groups\` (внутри группы — параллельно, группы — по очереди), текст задания \`text\` у агента и шага. Текст между \`<!--gen:flow.…-->\` и \`<!--/gen-->\` в \`SKILL.md\` собирается из \`flows\` — его не правь руками.
5. После правки \`settings.json\` перепиши метки: \`bb plugin rpc call ${pluginId} draft_render --input-file "D/rpc.json"\`.
6. Метки \`<!--p:…-->\`, \`<!--c:…-->\`, \`<!--a:…-->\`, \`<!--gen:…-->\` не удаляй и не меняй руками. Новое число, которое пользователь должен менять из панели, — новый параметр в \`params\` (\`group\`, \`label\`, \`type: "number"\`, \`value\`, \`min\`, \`max\`) и метка \`<!--p:ключ-->значение<!--/p-->\` в тексте. В блоках кода и в шапке \`SKILL.md\` меток нет: там \`plain\` — шаблон с \`{v}\`.
7. Модель, уровень, лимит агента — шапка файла в \`D/agents/\`. Включить или выключить агента — перенести файл между \`D/agents/\` и \`D/agents-disabled/\`. Новая роль — ещё и запись в \`settings.json\` → \`roles\`.
8. Стиль скилла: русский, коротко, дефис вместо тире, без Mermaid. Правь минимально: только то, о чём просили.

## Проверка и итог

1. \`bb plugin rpc call ${pluginId} draft_check --input-file "D/rpc.json"\` — нужно \`"problems": []\`.
2. \`bb plugin rpc call ${pluginId} draft_diff --input-file "D/rpc.json"\` — перечитай свою правку.
3. Запиши \`D/result.json\`:
   - готово: \`{"status":"ready","title":"<до 80 знаков: что изменено>","summary":"<2-4 строки: что и где>","risks":["<что может сломаться>"]}\`
   - не получилось: \`{"status":"failed","title":"<коротко>","summary":"<почему>"}\`
   Без \`result.json\` панель считает, что работа идёт.
4. Ответ в треде — 3 строки: что изменил, какие файлы, результат проверки. Эталонный прогон не запускай: пользователь запускает его кнопкой.
`;

