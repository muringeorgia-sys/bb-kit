// Shapes returned by core/core.mjs through server.ts.
export type Via = "Agent" | "SendMessage" | "AskUserQuestion" | "Codex" | "bash";
export type Call = { actor: string; label?: string; via?: Via; in?: string[]; out?: string[]; count?: number; text?: string };
export type StepKind = "stop" | "check" | "final" | null;
export type Step = {
  id: string;
  title: string;
  kind?: StepKind;
  gen?: boolean;
  joinPrev?: boolean;
  join?: string;
  seqJoin?: string;
  text?: string;
  note?: string;
  handoff?: string;
  concept?: boolean;
  groups: Call[][];
};
export type Flow = {
  id: string;
  label: string;
  short: string;
  trigger: string;
  result: string;
  gen: "list" | "waves" | null;
  numberFrom?: number;
  parallelLead?: string;
  steps: Step[];
};
export type Role = { id: string; role: string; does: string; writes: string[]; runtime?: string; fallback?: string };
export type ParamOption = { value: string; label: string };
export type Param = {
  group: string;
  label: string;
  type: "number" | "text" | "select" | "choice";
  value: string | number;
  min?: number;
  max?: number;
  options?: (string | ParamOption)[];
  slots?: Record<string, Record<string, string>>;
  plain?: { file: string; pattern?: string; slot?: string }[];
};
export type Settings = {
  version: number;
  note?: string;
  modelNames: Record<string, string>;
  params: Record<string, Param>;
  roles: Role[];
  rules: { title: string; text: string }[];
  flows: Record<string, Flow>;
};
export type AgentInfo = {
  name: string;
  rel: string;
  model: string;
  effort: string;
  tools: string;
  description: string;
  calls: number | null;
  minutes: number | null;
  state: "active" | "disabled";
  file: string;
  updatedAt: string;
};
export type Problem = { file: string; line: number; kind: string; key?: string; found?: string; expected?: string; text: string };
export type Occurrence = { file: string; line: number; slot?: string; plain?: boolean };
export type JournalEntry = { seq: number; ts: string; by: string; kind: string; title: string; files: string[]; version: string; prev: string | null; draft?: string; restoredFrom?: string };
export type Version = { id: string; ts: string; by: string; title: string };
export type DraftResult = { status: "ready" | "failed"; title?: string; summary?: string; risks?: string[] };
export type Draft = {
  id: string;
  ts: string;
  request: string;
  base: string | null;
  status: "work" | "ready" | "failed" | "accepted" | "rejected";
  result: DraftResult | null;
  eval: string | null;
  threadId?: string;
  evalThreadId?: string;
  threadStatus?: string | null;
  closedAt?: string;
};
export type EvalStatus = {
  last: { date: string; what: string; cases: string; auto: string; judge: string; cost: string; notes: string } | null;
  mtime?: string;
  after: number;
  runs: { ts: string; threadId: string; target: string }[];
};
export type DiffLine = { t: " " | "+" | "-"; text: string; a?: number; b?: number };
export type FileDiff = { rel: string; added: number; removed: number; hunks: { lines: DiffLine[] }[]; onlyMarkers: boolean; isNew?: boolean };
export type Preview = { files: FileDiff[]; moves: { name: string; disabled: boolean }[]; warnings?: string[]; problems?: Problem[] };
export type DraftPreview = Preview & { problems: Problem[] };
export type RunRow = { step: string; agent: string; model: string; tokens: string; time: string; status: string; file: string };
export type Run = {
  feature: string;
  sprint: string;
  mode: string | null;
  date: string | null;
  logPath: string;
  prdPath: string | null;
  designPath: string | null;
  rows: RunRow[];
  notes: string[];
};
export type Loaded = {
  settings: Settings;
  agents: AgentInfo[];
  occurrences: Record<string, Occurrence[]>;
  files: { rel: string; disabled: boolean; size: number; mtime: string }[];
  problems: Problem[];
  outside: { rel: string; kind: "new" | "changed" | "deleted" }[];
  journal: JournalEntry[];
  versions: Version[];
  drafts: Draft[];
  eval: EvalStatus;
  flowsRendered: Record<string, string>;
  paths: { skill: string; agents: string; data: string };
  runs: Run[];
  projectId: string;
  environmentId: string;
};
export type ApplyResult = { ok: boolean; message?: string; warnings?: string[]; entry?: JournalEntry };
